// Rasterises the world's land into the bitmap the globe samples, and writes it
// to src/lib/land.ts. Run with `npm run land`; the output is committed, so a
// build needs neither this script nor its two dev dependencies.
//
// The source is world-atlas's land-110m.json: Natural Earth's 1:110m land, which
// is in the public domain. One degree a cell is finer than the globe draws -- a
// tile there covers three to five degrees -- and the globe averages the cells
// under each tile, which is what softens its coastlines.
import { readFileSync, writeFileSync } from "node:fs"
import { createRequire } from "node:module"
import { feature } from "topojson-client"

const require = createRequire(import.meta.url)
const topology = JSON.parse(readFileSync(require.resolve("world-atlas/land-110m.json"), "utf8"))
const land = feature(topology, topology.objects.land)

const W = 360, H = 180

// Every ring of every polygon. Natural Earth cuts its polygons at the
// antimeridian, so each ring is planar in longitude and latitude, and the
// polygons do not overlap: one even-odd pass over all of them fills the land,
// holes included.
const rings = []
const collect = (geometry) => {
  if (geometry.type === "Polygon") rings.push(...geometry.coordinates)
  else if (geometry.type === "MultiPolygon") for (const p of geometry.coordinates) rings.push(...p)
  else if (geometry.type === "GeometryCollection") geometry.geometries.forEach(collect)
}
for (const f of land.type === "FeatureCollection" ? land.features : [land]) collect(f.geometry)

const bits = new Uint8Array((W * H) / 8)
for (let j = 0; j < H; j++) {
  const lat = 90 - (j + 0.5) * (180 / H)
  const xs = []
  for (const ring of rings) {
    for (let k = 0; k < ring.length - 1; k++) {
      const [x1, y1] = ring[k], [x2, y2] = ring[k + 1]
      if (y1 > lat !== y2 > lat) xs.push(x1 + ((lat - y1) * (x2 - x1)) / (y2 - y1))
    }
  }
  xs.sort((a, b) => a - b)
  for (let i = 0, crossed = 0; i < W; i++) {
    const lon = -180 + (i + 0.5) * (360 / W)
    while (crossed < xs.length && xs[crossed] < lon) crossed++
    if (crossed % 2) bits[(j * W + i) >> 3] |= 0x80 >> ((j * W + i) & 7)
  }
}

const b64 = Buffer.from(bits).toString("base64")
writeFileSync(
  new URL("../src/lib/land.ts", import.meta.url),
  `// Generated by scripts/landmask.mjs from Natural Earth 1:110m land (public domain).
// ${W} by ${H} cells of one degree, row by row from 90°N and from 180°W, one bit
// each with the first cell in the high bit. Do not edit by hand.
export const LAND_W = ${W}
export const LAND_H = ${H}
export const LAND_BITS =
${b64.match(/.{1,100}/g).map((line) => `  "${line}"`).join(" +\n")}
`,
)

// A look at the result, three degrees a column and six a row.
for (let j = 0; j < H; j += 6) {
  let line = ""
  for (let i = 0; i < W; i += 3) line += bits[(j * W + i) >> 3] & (0x80 >> ((j * W + i) & 7)) ? "#" : "."
  console.log(line)
}
console.log(`${rings.length} rings, ${b64.length} base64 characters`)
